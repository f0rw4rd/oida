# TCP defines its own state machine via _define_state_machine(), separate from CommonState
TCP_ALL_STATES = {
    "CLOSED",
    "LISTEN",
    "SYN_SENT",
    "SYN_RECEIVED",
    "ESTABLISHED",
    "FIN_WAIT_1",
    "FIN_WAIT_2",
    "CLOSE_WAIT",
    "CLOSING",
    "LAST_ACK",
    "TIME_WAIT",
}

# States a client-side fuzzer should actively reference
TCP_REQUIRED_STATES = {
    "CLOSED",  # Starting state for SYN
    "ESTABLISHED",  # Data transfer, attacks
    "SYN_SENT",  # After SYN, before SYN-ACK
    "SYN_RECEIVED",  # Server-side response
}

# Passive/intermediate states -- acceptable to have no requires_state
TCP_PASSIVE_STATES = {
    "LISTEN",  # Server-only
    "FIN_WAIT_1",  # Initiated close
    "FIN_WAIT_2",  # Waiting for remote FIN
    "CLOSE_WAIT",  # Waiting for app close
    "CLOSING",  # Simultaneous close
    "LAST_ACK",  # Waiting for final ACK
    "TIME_WAIT",  # Waiting for timeout
}


class TestTCPStateCoverage:
    """TCP fuzzer should reference key states in request definitions."""

    def test_tcp_has_state_aware_requests(self):
        """TCP fuzzer should have requests with requires_state."""
        fuzzer_class = PROTOCOL_FUZZERS.get("tcp")
        if fuzzer_class is None:
            require_service("tcp not available")

        requests = fuzzer_class.get_request_definitions()
        stateful = [r for r in requests if r.requires_state]
        assert len(stateful) > 0, (
            "TCP fuzzer has no requests with requires_state. "
            "TCP is a stateful protocol and should have state-aware requests."
        )

    def test_tcp_required_states_referenced(self):
        """Key TCP states should be referenced by at least one request."""
        fuzzer_class = PROTOCOL_FUZZERS.get("tcp")
        if fuzzer_class is None:
            require_service("tcp not available")

        requests = fuzzer_class.get_request_definitions()
        referenced_states = {
            str(r.requires_state) for r in requests if r.requires_state is not None
        }

        missing = TCP_REQUIRED_STATES - referenced_states
        assert not missing, (
            f"TCP: required states not referenced by any request: {missing}. "
            f"Referenced states: {sorted(referenced_states)}. "
            f"Add requests with requires_state for these states."
        )

    def test_tcp_established_has_multiple_requests(self):
        """ESTABLISHED state should have multiple requests (data transfer phase)."""
        fuzzer_class = PROTOCOL_FUZZERS.get("tcp")
        if fuzzer_class is None:
            require_service("tcp not available")

        requests = fuzzer_class.get_request_definitions()
        established_requests = [r for r in requests if str(r.requires_state) == "ESTABLISHED"]
        assert len(established_requests) >= 3, (
            f"TCP: ESTABLISHED state has only {len(established_requests)} requests. "
            f"Expected at least 3 (data, options, attacks). "
            f"Found: {[r.name for r in established_requests]}"
        )

    def test_tcp_closed_has_syn_request(self):
        """CLOSED state should have at least one SYN request."""
        fuzzer_class = PROTOCOL_FUZZERS.get("tcp")
        if fuzzer_class is None:
            require_service("tcp not available")

        requests = fuzzer_class.get_request_definitions()
        closed_requests = [r for r in requests if str(r.requires_state) == "CLOSED"]
        assert len(closed_requests) >= 1, (
            "TCP: CLOSED state has no requests. SYN handshake should start from CLOSED."
        )
        syn_requests = [r for r in closed_requests if "SYN" in r.name.upper()]
        assert len(syn_requests) >= 1, (
            f"TCP: CLOSED state has no SYN request. Found: {[r.name for r in closed_requests]}"
        )

    def test_tcp_passive_states_documented(self):
        """Unreferenced states should be in the known passive set."""
        fuzzer_class = PROTOCOL_FUZZERS.get("tcp")
        if fuzzer_class is None:
            require_service("tcp not available")

        requests = fuzzer_class.get_request_definitions()
        referenced_states = {
            str(r.requires_state) for r in requests if r.requires_state is not None
        }
        unreferenced = TCP_ALL_STATES - referenced_states

        # All unreferenced states should be in the known passive set
        unexpected = unreferenced - TCP_PASSIVE_STATES
        assert not unexpected, (
            f"TCP: states not referenced by any request and not in known passive set: "
            f"{unexpected}. Either add requests for these states or add them to "
            f"TCP_PASSIVE_STATES if they are intentionally unreferenced."
        )


