@pytest.mark.parametrize(
    "protocol_name,state_config",
    [(name, cfg) for name, cfg in sorted(STATEFUL_PROTOCOLS.items()) if cfg["must_have_pre_auth"]],
    ids=[name for name, cfg in sorted(STATEFUL_PROTOCOLS.items()) if cfg["must_have_pre_auth"]],
)
def test_pre_auth_requests_exist(protocol_name, state_config):
    """Protocols with auth must have pre-auth requests for unauthenticated testing."""
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        require_service(f"{protocol_name} not available")

    requests = fuzzer_class.get_request_definitions()
    pre_auth_states = {"PRE_AUTH", "CONNECTED", "ANY"}

    has_pre_auth = False
    for r in requests:
        if r.requires_state is None:
            continue
        state_vals = set()
        if isinstance(r.requires_state, list):
            for s in r.requires_state:
                state_vals.add(s.value if isinstance(s, CommonState) else str(s))
        elif isinstance(r.requires_state, CommonState):
            state_vals.add(r.requires_state.value)
        else:
            state_vals.add(str(r.requires_state))

        if state_vals & pre_auth_states:
            has_pre_auth = True
            break

    assert has_pre_auth, (
        f"{protocol_name}: no pre-auth requests found. "
        f"Auth protocols must have requests that run before authentication "
        f"(requires_state=PRE_AUTH, CONNECTED, or ANY). "
        f"States found: {_get_state_info(protocol_name)[1]}"
    )


