"""
Test state machine coverage for stateful fuzzers.

Stateful fuzzers (inheriting from StatefulFuzzer) must have:
1. All states reachable via state transitions
2. Requests referencing each defined state
3. Pre-auth requests for connection testing without credentials
4. Post-auth requests for testing after authentication

Applies only to protocols that define state requirements in RequestInfo.

Generated by fuzzer quality audit (2026-02-14).
"""

import pytest

from oida.fuzz.protocols import PROTOCOL_FUZZERS
from oida.fuzz.core.base_fuzzer import CommonState
from tests.service_gate import require_service

pytestmark = pytest.mark.core


def _get_state_info(protocol_name):
    """Extract state information from a protocol's request definitions.

    Returns:
        Tuple of (requests, states_required, categories)
        where states_required is the set of all state strings referenced.
    """
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        return [], set(), set()

    requests = fuzzer_class.get_request_definitions()
    states_required = set()
    categories = set()

    for r in requests:
        categories.add(r.category)
        if r.requires_state is not None:
            if isinstance(r.requires_state, list):
                for s in r.requires_state:
                    states_required.add(s.value if isinstance(s, CommonState) else str(s))
            elif isinstance(r.requires_state, CommonState):
                states_required.add(r.requires_state.value)
            else:
                states_required.add(str(r.requires_state))

    return requests, states_required, categories


