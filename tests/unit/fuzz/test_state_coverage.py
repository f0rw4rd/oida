@pytest.mark.parametrize(
    "protocol_name",
    sorted(STATEFUL_FUZZER_SUBCLASSES),
    ids=sorted(STATEFUL_FUZZER_SUBCLASSES),
)
def test_stateful_fuzzer_has_multiple_state_phases(protocol_name):
    """StatefulFuzzer subclasses should have requests in 2+ state phases."""
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        require_service(f"{protocol_name} not available")

    _, states_required, _ = _get_state_info(protocol_name)

    # Filter out ANY since it is not really a distinct phase.
    # ICS protocols like IEC104 legitimately use CONNECTED + ANY because they
    # have no authentication -- their state machine is connect-then-operate.
    # Require 2+ total states (including ANY) to ensure at least some state
    # awareness, but only require 2+ non-ANY phases for auth protocols.
    assert len(states_required) >= 2, (
        f"{protocol_name}: only {len(states_required)} state(s) "
        f"({sorted(states_required)}). StatefulFuzzer should have at least "
        f"2 state references (e.g., CONNECTED + ANY, or PRE_AUTH + AUTHENTICATED)."
    )


