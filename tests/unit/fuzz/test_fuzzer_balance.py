"""
Test that multi-category protocols have requests in all required categories.

Each protocol fuzzer should cover multiple attack categories:
- baseline: at least one connectivity/valid-packet request
- boundary or overflow: at least one boundary/overflow test for numeric protocols
- attack/injection/cve: at least one attack-oriented request for protocols with known CVEs

Protocols with fewer than 3 requests are exempt from balance checks.

Generated by fuzzer quality audit (2026-02-14).
Thresholds derived from actual category distributions in the codebase.
"""

