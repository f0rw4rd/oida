@pytest.mark.parametrize(
    "protocol_name,required_cats",
    sorted(REQUIRED_CATEGORIES.items()),
    ids=sorted(REQUIRED_CATEGORIES.keys()),
)
def test_required_categories_present(protocol_name, required_cats):
    """Protocol fuzzer covers all required categories."""
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        pytest.skip(f"{protocol_name} not available in PROTOCOL_FUZZERS")

    requests = fuzzer_class.get_request_definitions()
    actual_cats = {r.category for r in requests}

    missing = required_cats - actual_cats
    assert not missing, (
        f"{protocol_name}: missing required categories: {missing}. "
        f"Found categories: {sorted(actual_cats)}. "
        f"Requests: {[(r.name, r.category) for r in requests]}"
    )


@pytest.mark.parametrize(
    "protocol_name",
    sorted(REQUIRED_CATEGORIES.keys()),
    ids=sorted(REQUIRED_CATEGORIES.keys()),
)
def test_multi_request_fuzzers_have_category_diversity(protocol_name):
    """Fuzzers with 5+ requests should have at least 2 distinct categories."""
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        pytest.skip(f"{protocol_name} not available in PROTOCOL_FUZZERS")

    requests = fuzzer_class.get_request_definitions()
    if len(requests) < 5:
        pytest.skip(f"{protocol_name} has only {len(requests)} requests, skipping diversity check")

    actual_cats = {r.category for r in requests}
    assert len(actual_cats) >= MIN_CATEGORIES_FOR_MULTI_REQUEST, (
        f"{protocol_name}: only {len(actual_cats)} category(ies) "
        f"({sorted(actual_cats)}) across {len(requests)} requests. "
        f"Expected at least {MIN_CATEGORIES_FOR_MULTI_REQUEST} distinct categories."
    )


@pytest.mark.parametrize(
    "protocol_name",
    sorted(REQUIRED_CATEGORIES.keys()),
    ids=sorted(REQUIRED_CATEGORIES.keys()),
)
def test_baseline_request_exists(protocol_name):
    """Every multi-request fuzzer should have at least one baseline request.

    Accepts 'baseline' or 'quick_coverage' as baseline categories.
    Protocols with fewer than 3 requests are exempt.
    """
    fuzzer_class = PROTOCOL_FUZZERS.get(protocol_name)
    if fuzzer_class is None:
        pytest.skip(f"{protocol_name} not available in PROTOCOL_FUZZERS")

    requests = fuzzer_class.get_request_definitions()
    if len(requests) < 3:
        pytest.skip(f"{protocol_name} has <3 requests, baseline not required")

    baseline_cats = {"baseline", "quick_coverage", "discovery", "standard"}
    has_baseline = any(r.category in baseline_cats for r in requests)

    # Some protocols use the first request as an implicit baseline
    # or have "standard" category that serves this role
    if not has_baseline:
        # Check if any request name suggests baseline behavior
        baseline_names = {"baseline", "quick", "discovery", "connectivity", "standard"}
        has_baseline = any(any(kw in r.name.lower() for kw in baseline_names) for r in requests)

    assert has_baseline, (
        f"{protocol_name}: no baseline request found. "
        f"Categories present: {sorted({r.category for r in requests})}. "
        f"Every fuzzer should have at least one 'baseline' or "
        f"'quick_coverage' request for connectivity testing."
    )


